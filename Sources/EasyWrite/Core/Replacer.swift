import AppKit
import ApplicationServices
import CoreGraphics

/// Reads selected text through Accessibility and sends a validated paste to the source process.
/// Requires Accessibility permission to post events to other apps.
///
/// Selection capture never uses the clipboard. Temporary output pastes restore it only while owned.
@MainActor
final class Replacer {
    private let pasteboard: NSPasteboard
    private let command: ((CGKeyCode) -> Void)?
    private let schedule: (@escaping () -> Void) -> Void
    private let targetIsCurrent: ((SelectionTarget) -> Bool)?

    init(pasteboard: NSPasteboard = .general, command: ((CGKeyCode) -> Void)? = nil,
         schedule: @escaping (@escaping () -> Void) -> Void = {
             DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: DispatchWorkItem(block: $0))
         }, targetIsCurrent: ((SelectionTarget) -> Bool)? = nil) {
        self.pasteboard = pasteboard
        self.command = command
        self.schedule = schedule
        self.targetIsCurrent = targetIsCurrent
    }
    /// Raw data rather than NSPasteboardItems: an item can only be written to a pasteboard once,
    /// and a read followed by Replace restores twice.
    private var saved: [[NSPasteboard.PasteboardType: Data]] = []
    private var clipboardDirty = false
    private var ownedChangeCount: Int?
    /// Bumped by anything that supersedes a scheduled restore, so a restore that fires late
    /// can never overwrite a newer copy or the user's own clipboard.
    private var restoreGeneration = 0
    // .privateState => our synthetic events ignore physically-held modifier keys
    private let source = CGEventSource(stateID: .privateState)

    /// nspasteboard.org markers: clipboard managers (Clip 4 Breakfast, Maccy, Paste, …) skip
    /// items carrying these, so Easy Write's temporary paste never shows up in their history.
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func selectedText() -> String? {
        guard let element = focusedElement() else { return nil }
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &value) == .success
        else { return nil }
        return value as? String
    }

    /// Replaces the current selection with `newText`, then restores the clipboard.
    @discardableResult
    func replaceSelection(with newText: String, target: SelectionTarget) -> Bool {
        // From the reader card the clipboard was already restored, and the user may have
        // copied something since. Snapshot again so that newer content is what comes back.
        if clipboardDirty { restoreClipboard() }
        let before = pasteboard.changeCount
        saved = snapshot()
        // Reading rich data providers can block. Verify only after that work is finished.
        guard pasteboard.changeCount == before, isCurrent(target) else { saved = []; return false }
        restoreGeneration += 1
        let generation = restoreGeneration
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(newText, forType: .string)
        for t in Self.transientTypes { item.setString("", forType: t) }
        pasteboard.writeObjects([item])
        clipboardDirty = true
        ownedChangeCount = pasteboard.changeCount
        guard isCurrent(target), ownedChangeCount == pasteboard.changeCount else {
            restoreClipboard()
            return false
        }
        postCmd(virtualKey: 9, pid: target.pid) // never route a delayed key into another process
        // Slow targets (Electron, VMs, remote desktops) read the clipboard late; give them time.
        schedule { [weak self] in
            guard let self, self.restoreGeneration == generation else { return }
            self.restoreClipboard()
        }
        return true
    }

    /// Puts back what was on the clipboard before a temporary paste. Does nothing if Easy Write
    /// never changed it, so clipboard managers don't record a duplicate.
    func restoreClipboard() {
        guard clipboardDirty else { return }
        clipboardDirty = false
        let stillOwned = ownedChangeCount == pasteboard.changeCount
        ownedChangeCount = nil
        defer { saved = [] }
        guard stillOwned else { return } // a newer copy belongs to the user, not this operation
        pasteboard.clearContents()
        let items = saved.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    /// Copies text for the user to keep (a real clipboard item, not a transient one).
    func copyForUser(_ text: String) {
        restoreGeneration += 1                       // a late restore must not undo this copy
        clipboardDirty = false
        ownedChangeCount = nil
        saved = []
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    // MARK: Accessibility helpers

    private func isCurrent(_ target: SelectionTarget) -> Bool {
        targetIsCurrent?(target) ?? Self.sameSelection(target, selectionTarget())
    }

    /// An app PID alone cannot identify a browser tab or a text field.
    struct SelectionTarget {
        var pid: pid_t
        var element: AXUIElement
        var window: AXUIElement
        var range: CFRange
        var text: String
    }

    static func sameSelection(_ original: SelectionTarget?, _ current: SelectionTarget?) -> Bool {
        guard let a = original, let b = current else { return false }
        return a.pid == b.pid && CFEqual(a.element, b.element) && CFEqual(a.window, b.window)
            && a.range.location == b.range.location && a.range.length == b.range.length
            && a.text == b.text
    }

    func selectionTarget() -> SelectionTarget? {
        guard let element = focusedElement() else { return nil }
        var pid: pid_t = 0
        guard AXUIElementGetPid(element, &pid) == .success else { return nil }
        var windowValue: CFTypeRef?
        var rangeValue: CFTypeRef?
        var textValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXWindowAttribute as CFString, &windowValue) == .success,
              let window = windowValue, CFGetTypeID(window) == AXUIElementGetTypeID(),
              AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let rangeObject = rangeValue, CFGetTypeID(rangeObject) == AXValueGetTypeID(),
              AXUIElementCopyAttributeValue(element, kAXSelectedTextAttribute as CFString, &textValue) == .success,
              let text = textValue as? String, !text.isEmpty else { return nil }
        var range = CFRange(location: 0, length: 0)
        guard AXValueGetValue(rangeObject as! AXValue, .cfRange, &range), range.length > 0 else { return nil }
        return SelectionTarget(pid: pid, element: element, window: window as! AXUIElement, range: range, text: text)
    }

    private func focusedElement() -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(system, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let v = value, CFGetTypeID(v) == AXUIElementGetTypeID() else { return nil }
        return (v as! AXUIElement)
    }

    /// Whether the focused element accepts text, so read mode can offer Replace only where
    /// pasting will actually work.
    func focusedIsEditable() -> Bool {
        guard let el = focusedElement() else { return false }
        var settable: DarwinBoolean = false
        guard AXUIElementIsAttributeSettable(el, kAXValueAttribute as CFString, &settable) == .success else { return false }
        return settable.boolValue
    }

    /// Screen rectangle of the current selection in Cocoa coordinates, when the focused app
    /// exposes it. Used to open the Bar right next to the text. Many apps do; some don't.
    func selectionBounds() -> NSRect? {
        guard let el = focusedElement() else { return nil }
        var rangeValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &rangeValue) == .success,
              let range = rangeValue else { return nil }
        var boundsValue: CFTypeRef?
        guard AXUIElementCopyParameterizedAttributeValue(el, kAXBoundsForRangeParameterizedAttribute as CFString,
                                                         range, &boundsValue) == .success,
              let b = boundsValue, CFGetTypeID(b) == AXValueGetTypeID() else { return nil }
        var rect = CGRect.zero
        guard AXValueGetValue(b as! AXValue, .cgRect, &rect), rect.width > 0 || rect.height > 0 else { return nil }
        // AX uses a top-left origin on the primary display; Cocoa uses bottom-left.
        let primaryHeight = NSScreen.screens.first?.frame.height ?? 0
        return NSRect(x: rect.minX, y: primaryHeight - rect.maxY, width: rect.width, height: rect.height)
    }

    // MARK: Private

    private func postCmd(virtualKey: CGKeyCode, pid: pid_t) {
        if let command { command(virtualKey); return }
        let down = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: true)
        down?.flags = .maskCommand
        let up = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: false)
        up?.flags = .maskCommand
        down?.postToPid(pid)
        up?.postToPid(pid)
    }

    /// Copies the clipboard's data so it can be put back. Dynamic ("dyn.") and promised types
    /// are skipped: reading them makes the source app render every format on demand, which for
    /// a large spreadsheet range or a file promise can stall for seconds.
    private func snapshot() -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                let raw = type.rawValue
                if raw.hasPrefix("dyn.") || raw.localizedCaseInsensitiveContains("promise") { continue }
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
    }
}
